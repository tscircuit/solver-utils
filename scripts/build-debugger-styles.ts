import { writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import postcss from "postcss"
import tailwindcss from "tailwindcss"

const scope = ".tscircuit-solver-debugger"
const result = await postcss([
  tailwindcss({
    content: [fileURLToPath(new URL("../lib/react/**/*.tsx", import.meta.url))],
  }),
]).process("@tailwind base; @tailwind utilities;", { from: undefined })

// Keep both utilities and their required form, border and transform defaults
// inside the debugger. Its host document retains its own styling.
result.root.walkRules((rule) => {
  if (
    rule.parent?.type === "atrule" &&
    rule.parent.name.endsWith("keyframes")
  ) {
    return
  }
  // The body inherits the html baseline; the debugger uses that baseline itself.
  if (rule.selector === "body") {
    rule.remove()
    return
  }
  rule.selectors = [
    ...new Set(
      rule.selectors.flatMap((selector) => {
        if (["html", ":host"].includes(selector)) return [scope]
        if (selector === "*") return [scope, `${scope} *`]
        if (/^::?(before|after|backdrop)$/.test(selector)) {
          return [`${scope}${selector}`, `${scope} ${selector}`]
        }
        return [`${scope} ${selector}`]
      }),
    ),
  ]
})

await writeFile(
  new URL("../lib/react/debugger-styles.generated.ts", import.meta.url),
  `// Generated by scripts/build-debugger-styles.ts.\nexport default ${JSON.stringify(result.root.toString())}\n`,
)
